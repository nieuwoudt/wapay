/**
 * Generates docs/CONVERSATION_KNOWLEDGE_BASE.md from lib/how-it-works.js,
 * lib/fee-facts.js and lib/ott-acceptance.js so the reference document and
 * the bot can never disagree. Run: node scripts/gen-knowledge-base-doc.mjs
 */
import { writeFileSync } from 'node:fs';
import { TOPICS } from '../lib/how-it-works.js';
import { feeAnswer } from '../lib/fee-facts.js';
import { ottAcceptedFacts, ottRedemptionFacts, OTT_ACCEPTED, OTT_NOT_ACCEPTED, OTT_SOLD_AT, OTT_RESEARCHED_ON } from '../lib/ott-acceptance.js';
import { advertisedFuelPartners } from '../lib/spend-catalogue.js';

const ctxLive = { withdrawLive: true, wicodeLive: true, fuelPartners: advertisedFuelPartners().map((p) => p.name), ottFacts: ottAcceptedFacts() };
const ctxOff = { ...ctxLive, withdrawLive: false, wicodeLive: false };
const prev = process.env.WAPAY_PAYOUT_ENABLED; process.env.WAPAY_PAYOUT_ENABLED = 'true';
const lines = [
  '# WaPay conversation knowledge base',
  '',
  '*Generated by `scripts/gen-knowledge-base-doc.mjs` from `lib/how-it-works.js`, `lib/fee-facts.js` and `lib/ott-acceptance.js`. Do not edit by hand: change the data and regenerate. Every number comes from the constants and fee functions the flows use. These are the exact English texts the bot sends (the processor localizes them); the AI receives the same facts in its knowledge block.*',
  '',
  '## How the bot decides',
  '',
  '1. A price question (`matchFeeAsk`) gets the fee schedule, before anything else.',
  '2. A question about a capability or a process (`matchHowItWorksAsk`) gets the topic answer below. A message with an amount or a number is a command, never a question.',
  '3. A withdraw command (`matchWithdrawAsk`) starts the withdraw flow. Inside any withdraw step, a question is answered and the step is repeated (`stepInputParses`).',
  '4. Only then does the keyword router run, and only its fall-through reaches the AI, which carries FEES + HOW IT WORKS + the OTT acceptance facts.',
  '',
  '## Topics (bot answers, payouts live, fuel live)',
  '',
];
for (const [id, t] of Object.entries(TOPICS)) {
  lines.push(`### ${t.title}`, '', `Topic id: \`${id}\`. Detection: \`${t.keywords.source}\``, '', '```text', t.answer(ctxLive), '```', '');
  const off = t.answer(ctxOff);
  if (off !== t.answer(ctxLive)) lines.push('When the switch is off:', '', '```text', off, '```', '');
}
lines.push('## Fees (deterministic answer to "what does it cost")', '', '```text', feeAnswer('general'), '```', '');
lines.push(`## OTT voucher acceptance (researched ${OTT_RESEARCHED_ON})`, '', ottAcceptedFacts(), '', ottRedemptionFacts(), '', '| Accepts OTT as payment | For |', '|---|---|');
for (const m of OTT_ACCEPTED) lines.push(`| ${m.name} | ${m.what} |`);
lines.push('', '| Asked about, does NOT accept | Sells OTT vouchers | Note |', '|---|---|---|');
for (const m of OTT_NOT_ACCEPTED) lines.push(`| ${m.name} | ${m.sells ? 'yes' : 'no'} | ${m.note || ''} |`);
lines.push('', `Where to buy one with cash: ${OTT_SOLD_AT}.`, '', 'Betting operators are the majority of OTT partners and are deliberately absent: Meta policy forbids naming them on the WhatsApp Business number.', '');
writeFileSync(new URL('../docs/CONVERSATION_KNOWLEDGE_BASE.md', import.meta.url), lines.join('\n'));
if (prev === undefined) delete process.env.WAPAY_PAYOUT_ENABLED; else process.env.WAPAY_PAYOUT_ENABLED = prev;
console.log('wrote docs/CONVERSATION_KNOWLEDGE_BASE.md', lines.length, 'lines');
