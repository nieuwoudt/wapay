#!/usr/bin/env node
/**
 * Assemble the WaPay Money Map from its sources.
 *
 *   node docs/commercials/assemble.mjs
 *
 * Writes docs/commercials/money-map.html (publish it to the artifact URL in
 * docs/HANDOVER_COMMERCIALS_V1.md, keeping the link) and rewrites the generated
 * block between MONEY_MAP_TABLES markers in docs/COMMERCIALS.md, so the text
 * master and the dashboard always show the same rows. Run sync-from-code.mjs
 * first whenever a fee in code changed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '..', '..');
const require = createRequire(import.meta.url);
const MM = require('./model.js');
const rowsDoc = JSON.parse(readFileSync(path.join(dir, 'rows.json'), 'utf8'));
const facts = JSON.parse(readFileSync(path.join(dir, 'code-facts.json'), 'utf8'));
const modelSrc = readFileSync(path.join(dir, 'model.js'), 'utf8');
const AMOUNTS = rowsDoc.referenceAmountsCents;
const ORDER = ['in', 'out', 'vend', 'paid', 'send', 'biz', 'fixed'];
const STATE_LABEL = { LIVE: 'live', PILOT: 'pilot', BUILT: 'built', OFF: 'rail off', NOT_BUILT: 'not built' };
const amtLabel = (c) => 'R' + String(c / 100).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const needsDecision = (row) => [row.cost, row.price, row.commission, row.proposedPrice].filter(Boolean).some((n) => n.status !== 'SIGNED' && n.status !== 'LIVE');
const prettyDate = (iso) => { const d = new Date(iso + 'T00:00:00Z'); return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }); };

// ---------------------------------------------------------------- HTML
let html = readFileSync(path.join(dir, 'money-map.template.html'), 'utf8');
const safeJson = (o) => JSON.stringify(o).replace(/</g, '\\u003c');
html = html.replace('<!--MODEL_JS-->', modelSrc.replace(/\n?if \(typeof module[^\n]*\n?/, '\n'));
html = html.replace('<!--ROWS_JSON-->', safeJson(rowsDoc));
html = html.replace('<!--FACTS_JSON-->', safeJson({ build: facts.build, generatedAt: facts.generatedAt, rowsVersion: facts.rowsVersion }));
html = html.replace(/<!--VERSION-->/g, rowsDoc.version);
html = html.replace(/<!--DATE-->/g, prettyDate(rowsDoc.date));
html = html.replace(/<!--BUILD-->/g, facts.build);
html = html.replace('<!--GENERATED-->', new Date(facts.generatedAt).toISOString().slice(0, 16).replace('T', ' ') + ' UTC');
writeFileSync(path.join(dir, 'money-map.html'), html);

// ---------------------------------------------------------------- Markdown block
const R = MM.rand;
const mdEsc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const marginText = (r) => {
  if (!r.applicable) return `n/a (${r.reason})`;
  if (r.marginCents == null) return '? (cost not on file)';
  const main = R(r.marginCents, { sign: true });
  return r.marginBookedCents != null && r.marginBookedCents !== r.marginCents ? `${main} (ledger books ${R(r.marginBookedCents)})` : main;
};
const priceText = (row, r) => {
  if (!r.applicable) return 'n/a';
  const p = row.price || {};
  if (p.kind === 'faceDiscount') return `${R(r.creditedCents)} credited`;
  if (p.kind === 'face') return 'face';
  if (p.kind === 'none' || r.priceCents == null) return 'no price set';
  return R(r.priceCents);
};
const costText = (row, r) => {
  if (!r.applicable) return 'n/a';
  if (r.costUnknown || (r.costExCents == null && r.costInclCents == null)) return 'not on file';
  return `${R(r.costExCents)} / ${R(r.costInclCents)}`;
};
const statusText = (row) => [['cost', row.cost], ['price', row.price], ['commission', row.commission], ['proposed', row.proposedPrice]].filter(([, n]) => n).map(([k, n]) => `${k} ${n.status}`).join(' · ');

const lines = [];
lines.push(`<!-- MONEY_MAP_TABLES:BEGIN -->`);
lines.push(`<!-- Generated by docs/commercials/assemble.mjs from rows.json + model.js + code-facts.json. Do not edit by hand: change rows.json and re-run. -->`);
lines.push(`*Money Map data version ${rowsDoc.version}, ${prettyDate(rowsDoc.date)}, verified against build ${facts.build}. Amounts in rand; "cost" is what the counterparty charges WaPay on that transaction, ex VAT / incl the VAT WaPay cannot recover; "margin" is what WaPay keeps after that cost (negative = WaPay pays to run the transaction). n/a = the amount is outside the row's limits.*`);
lines.push('');
for (const key of ORDER) {
  const sec = rowsDoc.sections[key];
  const rows = rowsDoc.rows.filter((r) => r.section === key);
  if (!rows.length) continue;
  lines.push(`### ${sec.title}`);
  lines.push('');
  lines.push(`${sec.blurb}`);
  lines.push('');
  if (key === 'fixed') {
    lines.push('| Cost line | Counterparty | State | Cost | Recovered by | Status | Source |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const row of rows) {
      lines.push(`| ${mdEsc(row.name)} | ${mdEsc(row.counterparty)} | ${STATE_LABEL[row.productState]} | ${mdEsc(MM.describeRate(row.cost))} | ${mdEsc(MM.describePrice(row.price))} | ${statusText(row)} | ${mdEsc(row.cost.source)} |`);
    }
    lines.push('');
    continue;
  }
  lines.push('**Terms and status**');
  lines.push('');
  lines.push('| Component | Counterparty | State | Who pays WaPay | Our cost (rate) | Customer pays (rule) | Supplier pays us | Status | Source |');
  lines.push('|---|---|---|---|---|---|---|---|---|');
  for (const row of rows) {
    const com = row.commission && row.commission.bps != null ? `${(row.commission.bps / 100).toFixed(2).replace(/\.?0+$/, '')}% of face${row.commission.bookedBps !== row.commission.bps ? ` (ledger books ${((row.commission.bookedBps || 0) / 100).toFixed(2).replace(/\.?0+$/, '')}%)` : ''}` : (row.commission ? 'not on file' : '');
    const price = MM.describePrice(row.price) + (row.proposedPrice ? `; proposed ${MM.describePrice(row.proposedPrice)}` : '');
    const src = [row.cost && `cost: ${row.cost.source}`, row.price && `price: ${row.price.source}`, row.commission && `commission: ${row.commission.source}`, row.proposedPrice && `proposed: ${row.proposedPrice.source}`, row.notes && `note: ${row.notes}`, row.competitors && row.competitors.length && `market: ${row.competitors.map((c) => `${c.name} ${c.price}`).join('; ')}`].filter(Boolean).join(' ');
    lines.push(`| **${mdEsc(row.name)}**${row.productNote ? ` (${mdEsc(row.productNote)})` : ''} | ${mdEsc(row.counterparty)} | ${STATE_LABEL[row.productState]} | ${mdEsc(MM.PAYER_LABEL[row.payer])} | ${mdEsc(MM.describeRate(row.cost))} | ${mdEsc(price)} | ${mdEsc(com)} | ${statusText(row)} | ${mdEsc(src)} |`);
  }
  lines.push('');
  lines.push('**At the five reference amounts: customer pays · our cost ex VAT / incl VAT · margin**');
  lines.push('');
  lines.push(`| Component | ${AMOUNTS.map(amtLabel).join(' | ')} |`);
  lines.push(`|---|${AMOUNTS.map(() => '---').join('|')}|`);
  for (const row of rows) {
    const cells = AMOUNTS.map((a) => {
      const r = MM.compute(row, a);
      if (!r.applicable) return `n/a (${r.reason})`;
      return `${priceText(row, r)} · ${costText(row, r)} · **${marginText(r)}**`;
    });
    lines.push(`| ${mdEsc(row.name)} | ${cells.join(' | ')} |`);
  }
  lines.push('');
}
lines.push(`### Sign-off list: every ASSUMED, PROPOSED or UNKNOWN number, one question each`);
lines.push('');
let n = 0;
for (const row of rowsDoc.rows.filter((r) => r.question)) {
  n += 1;
  const also = rowsDoc.rows.filter((r) => r.questionRef === row.id).map((r) => r.name);
  lines.push(`${n}. **${mdEsc(row.name)}.** ${mdEsc(row.question)} *(${mdEsc(row.owner)}; ${statusText(row)}${also.length ? `; also covers: ${mdEsc(also.join(', '))}` : ''})*`);
}
for (const q of rowsDoc.crossCuttingQuestions || []) {
  n += 1;
  lines.push(`${n}. **Across the map.** ${mdEsc(q.question)} *(${mdEsc(q.owner)}; ${mdEsc(q.source)})*`);
}
lines.push('');
lines.push(`<!-- MONEY_MAP_TABLES:END -->`);
const block = lines.join('\n');

const mdPath = path.join(root, 'docs', 'COMMERCIALS.md');
let md = readFileSync(mdPath, 'utf8');
const re = /<!-- MONEY_MAP_TABLES:BEGIN -->[\s\S]*?<!-- MONEY_MAP_TABLES:END -->/;
if (!re.test(md)) throw new Error('docs/COMMERCIALS.md has no MONEY_MAP_TABLES markers');
md = md.replace(re, block);
writeFileSync(mdPath, md);

const statusCounts = {};
for (const row of rowsDoc.rows) for (const x of [row.cost, row.price, row.commission, row.proposedPrice].filter(Boolean)) statusCounts[x.status] = (statusCounts[x.status] || 0) + 1;
console.log(`assembled money-map.html (${html.length} chars) and the COMMERCIALS.md block (${rowsDoc.rows.length} rows, ${n} questions; statuses ${JSON.stringify(statusCounts)}; ${rowsDoc.rows.filter(needsDecision).length} rows need a decision)`);
